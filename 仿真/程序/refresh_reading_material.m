function refresh_reading_material()
% Keep the few human-facing PNG copies in sync after the MATLAB entry points.
% FIG files stay at their original result paths; do not duplicate them here.
folder=fileparts(fileparts(mfilename('fullpath')));
destination=fullfile(folder,'00_重点看');
if ~isfolder(destination),mkdir(destination);end
files={fullfile('结果','CC_step.png'),'01_恒流设定变化.png'; ...
       fullfile('结果','CC_line_step.png'),'02_输入电压变化.png'; ...
       fullfile('结果','Overcharge.png'),'03_过充保护.png'; ...
       fullfile('结果','Boost.png'),'04_放电稳压.png'; ...
       fullfile('结果','Auto_ramp.png'),'05_自动充放电.png'; ...
       fullfile('方案对比','结果','发挥2_往返调压对比.png'),'06_自动策略比较.png'; ...
       fullfile('方案对比','结果','基本4_测量与显示精度对比.png'),'07_电流测量方案比较.png'; ...
       fullfile('方案对比','结果','发挥1_频率与估计损耗.png'),'08_开关频率与效率.png'; ...
       fullfile('结果','AUTO2_32至38V突变.png'),'09_AUTO2输入突变.png'};
for k=1:size(files,1)
    source=fullfile(folder,files{k,1});
    if isfile(source),copyfile(source,fullfile(destination,files{k,2}));end
end
end
